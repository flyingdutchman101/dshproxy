'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const {classify} = require('../src/video/picker/classify');
const notice = '[model changed: assistant turns above this point were generated by dshproxy-lanes/lane-main; the session continues with dshproxy-video/seedance-2.5/480p/krea]';
const user = content => ({role:'user',content});
const quote = {role:'assistant',content:'Sample quote\nQuote Q-6263SZJNFW428VYS'};
test('switching models quotes the scene, never the routing notice', () => {
  const scene = 'A man eating an ice cream sandwich, buying life insurance.';
  for (const messages of [[user(scene),user(notice)], [user([scene,notice].map(text=>({type:'text',text})))]] ) {
    assert.equal(classify({messages}).prompt, scene);
  }
  assert.equal(classify({messages:[quote,user(notice)]}).kind, 'silent');
  assert.notEqual(classify({messages:[quote,user('yes'),user(notice)]}).kind, 'confirm');
});
